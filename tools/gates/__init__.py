"""门禁脚本（gates）—— 跑一次就知道「某条纪律还成立吗」的机器判据。

★ 为什么单独一个目录，而不是继续平铺在 `tools/` 下
------------------------------------------------
`tools/` 里混着三类东西：门禁（跑完给退出码）、一次性探针（probe_*）、
运维脚本（remote_*）。它们的生命周期完全不同——门禁要进 CI、要有人维护、
要能单独跑；探针用完就该删。平铺在一起时，「哪些是必须一直绿的」
只能靠人记。分目录是让这件事有结构。

★ 本目录的约定
--------------
1. 每个脚本都能**单独跑**（`python tools/gates/<name>.py`），不依赖 pytest；
2. 退出码 0 = 通过，1 = 有违规，2 留给「环境坏了没法判」；
3. 判不了就打印「跳过」+ 原因，**不打印通过**——门禁假绿比没有门禁更坏；
4. 路径一律从 `tools/paths.py` 取，不自己数 `parents[N]`。

★ 登记
------
每个门禁都要登记在 `tools/gate_registry.py` 里（id / 路径 / 说明 / 是否拦 /
有无回归测试）。未登记的脚本不一定是错，但必须能被列出来——
「有一道门禁没人知道它在跑」和「没有这道门禁」是同一件事。
"""
